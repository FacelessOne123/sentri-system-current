#!/usr/bin/env python3
import sys
import json
import openpyxl
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
from openpyxl.utils import get_column_letter

def build_excel(data, out_path):
    wb = openpyxl.Workbook()
    ws = wb.active
    
    export_type = data.get('export_type', 'reports')
    title_text = data.get('title', 'OFFICIAL INCIDENT TELEMETRY REPORT')
    scope_text = data.get('scope', 'City of Imus (All Barangays)')
    timeframe = data.get('timeframe', 'All Time')
    generated_by = data.get('generated_by', 'System')
    generated_at = data.get('generated_at', '')
    summary = data.get('summary', {})
    headers = data.get('headers', [])
    rows = data.get('rows', [])
    
    ws.title = 'Incident Telemetry' if export_type == 'reports' else 'Audit Trail'
    ws.views.sheetView[0].showGridLines = True

    # Color Palette (SenTri Brand)
    TEAL_HEADER = '0F766E'      # Primary SenTri Teal
    TEAL_SUB = '115E59'         # Deep Teal
    HEADER_BG = '134E4A'        # Column Header Background
    BORDER_CLR = 'CBD5E1'       # Slate 300
    ZEBRA_BG = 'F8FAFC'         # Slate 50
    
    # Status Alert Colors
    DANGER_BG = 'FEE2E2'; DANGER_TXT = 'B91C1C'
    CAUTION_BG = 'FEF3C7'; CAUTION_TXT = 'B45309'
    SAFE_BG = 'DCFCE7'; SAFE_TXT = '15803D'

    thin_border = Border(
        left=Side(style='thin', color=BORDER_CLR),
        right=Side(style='thin', color=BORDER_CLR),
        top=Side(style='thin', color=BORDER_CLR),
        bottom=Side(style='thin', color=BORDER_CLR)
    )

    banner_cols = min(max(len(headers), 5), 8)
    banner_col_letter = get_column_letter(banner_cols)
    last_col_letter = get_column_letter(len(headers))

    # ── 1. Top Brand Banner ──
    ws.merge_cells(f'A2:{banner_col_letter}2')
    c2 = ws['A2']
    c2.value = "SENTRI | CITIZEN-DRIVEN HAZARD REPORTING & DISASTER RESPONSE SYSTEM"
    c2.font = Font(name='Segoe UI', size=12, bold=True, color='FFFFFF')
    c2.fill = PatternFill(start_color=TEAL_HEADER, end_color=TEAL_HEADER, fill_type='solid')
    c2.alignment = Alignment(horizontal='center', vertical='center')
    ws.row_dimensions[2].height = 28

    ws.merge_cells(f'A3:{banner_col_letter}3')
    c3 = ws['A3']
    c3.value = f"{title_text.upper()} • CITY OF IMUS, CAVITE"
    c3.font = Font(name='Segoe UI', size=9.5, bold=False, color='E0F2FE')
    c3.fill = PatternFill(start_color=TEAL_SUB, end_color=TEAL_SUB, fill_type='solid')
    c3.alignment = Alignment(horizontal='center', vertical='center')
    ws.row_dimensions[3].height = 20

    # ── 2. Telemetry Meta Info ──
    ws['A5'] = "Jurisdiction / Scope:"
    ws['A5'].font = Font(name='Segoe UI', size=9, bold=True, color='475569')
    ws['B5'] = scope_text
    ws['B5'].font = Font(name='Segoe UI', size=9, bold=True, color='0F172A')

    ws['D5'] = "Report Timeframe:"
    ws['D5'].font = Font(name='Segoe UI', size=9, bold=True, color='475569')
    ws['E5'] = timeframe
    ws['E5'].font = Font(name='Segoe UI', size=9, bold=True, color='0F172A')

    ws['A6'] = "Generated By:"
    ws['A6'].font = Font(name='Segoe UI', size=9, bold=True, color='475569')
    ws['B6'] = generated_by
    ws['B6'].font = Font(name='Segoe UI', size=9, color='334155')

    ws['D6'] = "Generated At:"
    ws['D6'].font = Font(name='Segoe UI', size=9, bold=True, color='475569')
    ws['E6'] = generated_at
    ws['E6'].font = Font(name='Segoe UI', size=9, color='334155')

    # Metric scorecard row (if summary available)
    if export_type == 'reports' and summary:
        ws['A7'] = "Telemetry Summary:"
        ws['A7'].font = Font(name='Segoe UI', size=9, bold=True, color='475569')

        ws['B7'] = f"Total: {summary.get('total', 0)}"
        ws['B7'].font = Font(name='Segoe UI', size=9, bold=True, color='0F172A')
        ws['B7'].fill = PatternFill(start_color='F1F5F9', end_color='F1F5F9', fill_type='solid')
        ws['B7'].alignment = Alignment(horizontal='center')
        ws['B7'].border = thin_border

        ws['C7'] = f"Critical: {summary.get('dangerous', 0)}"
        ws['C7'].font = Font(name='Segoe UI', size=9, bold=True, color=DANGER_TXT)
        ws['C7'].fill = PatternFill(start_color=DANGER_BG, end_color=DANGER_BG, fill_type='solid')
        ws['C7'].alignment = Alignment(horizontal='center')
        ws['C7'].border = thin_border

        ws['D7'] = f"Warning: {summary.get('caution', 0)}"
        ws['D7'].font = Font(name='Segoe UI', size=9, bold=True, color=CAUTION_TXT)
        ws['D7'].fill = PatternFill(start_color=CAUTION_BG, end_color=CAUTION_BG, fill_type='solid')
        ws['D7'].alignment = Alignment(horizontal='center')
        ws['D7'].border = thin_border

        ws['E7'] = f"Safe: {summary.get('safe', 0)}"
        ws['E7'].font = Font(name='Segoe UI', size=9, bold=True, color=SAFE_TXT)
        ws['E7'].fill = PatternFill(start_color=SAFE_BG, end_color=SAFE_BG, fill_type='solid')
        ws['E7'].alignment = Alignment(horizontal='center')
        ws['E7'].border = thin_border

    start_table_row = 9

    # ── 3. Table Headers ──
    ws.row_dimensions[start_table_row].height = 24
    for col_idx, h_text in enumerate(headers, start=1):
        cell = ws.cell(row=start_table_row, column=col_idx, value=h_text)
        cell.font = Font(name='Segoe UI', size=9.5, bold=True, color='FFFFFF')
        cell.fill = PatternFill(start_color=HEADER_BG, end_color=HEADER_BG, fill_type='solid')
        cell.alignment = Alignment(horizontal='center', vertical='center', wrap_text=True)
        cell.border = thin_border

    # ── 4. Table Data Rows ──
    cur_row = start_table_row + 1
    for r_idx, row_values in enumerate(rows):
        is_even = (r_idx % 2 == 1)
        row_fill = PatternFill(start_color=ZEBRA_BG, end_color=ZEBRA_BG, fill_type='solid') if is_even else PatternFill(fill_type=None)
        ws.row_dimensions[cur_row].height = 20

        for col_idx, val in enumerate(row_values, start=1):
            cell = ws.cell(row=cur_row, column=col_idx, value=val)
            cell.font = Font(name='Segoe UI', size=9, color='0F172A')
            cell.border = thin_border
            cell.fill = row_fill
            cell.alignment = Alignment(vertical='center')

            h_name = headers[col_idx - 1] if col_idx - 1 < len(headers) else ''
            val_str = str(val or '')

            # Incident Code or Audit Code
            if 'Code' in h_name or 'Audit Entry' in h_name:
                cell.font = Font(name='Segoe UI', size=9, bold=True, color='0F766E')
                cell.alignment = Alignment(horizontal='center', vertical='center')

            # Severity / Status badge styling
            if 'Severity' in h_name or 'Status' in h_name:
                cell.alignment = Alignment(horizontal='center', vertical='center')
                if 'CRITICAL' in val_str or 'DANGEROUS' in val_str:
                    cell.fill = PatternFill(start_color=DANGER_BG, end_color=DANGER_BG, fill_type='solid')
                    cell.font = Font(name='Segoe UI', size=9, bold=True, color=DANGER_TXT)
                elif 'WARNING' in val_str or 'CAUTION' in val_str:
                    cell.fill = PatternFill(start_color=CAUTION_BG, end_color=CAUTION_BG, fill_type='solid')
                    cell.font = Font(name='Segoe UI', size=9, bold=True, color=CAUTION_TXT)
                elif 'SAFE' in val_str or 'RESOLVED' in val_str:
                    cell.fill = PatternFill(start_color=SAFE_BG, end_color=SAFE_BG, fill_type='solid')
                    cell.font = Font(name='Segoe UI', size=9, bold=True, color=SAFE_TXT)

            # Numbers / Coordinates / Dates
            if any(k in h_name for k in ['Latitude', 'Longitude', 'Radius', 'Trust', 'Doubts', 'Duration']):
                cell.alignment = Alignment(horizontal='center', vertical='center')
            elif any(k in h_name for k in ['Date', 'At', 'Timestamp']):
                cell.alignment = Alignment(horizontal='center', vertical='center')

        cur_row += 1

    # Auto-fit column widths with padding
    for col in ws.iter_cols(min_row=start_table_row, max_row=cur_row - 1):
        max_len = 0
        col_letter = get_column_letter(col[0].column)
        for c in col:
            val_str = str(c.value or '')
            if len(val_str) > max_len:
                max_len = len(val_str)
        ws.column_dimensions[col_letter].width = max(max_len + 4, 12)

    # Enable AutoFilter on table headers
    ws.auto_filter.ref = f"A{start_table_row}:{last_col_letter}{cur_row - 1}"

    wb.save(out_path)

if __name__ == '__main__':
    if len(sys.argv) < 3:
        print("Usage: generate_export_xlsx.py <input_json> <output_xlsx>", file=sys.stderr)
        sys.exit(1)

    json_path = sys.argv[1]
    out_path = sys.argv[2]

    with open(json_path, 'r', encoding='utf-8') as f:
        data = json.load(f)

    build_excel(data, out_path)
    print("OK")
